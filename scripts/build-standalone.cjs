const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');

function standalone() {
  const source = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
  return '<!-- Generated by scripts/build-standalone.cjs. Edit index.html and local scripts. -->\n' +
    source.replace(/<script src="(db-sync\.js|training-engine\.js)"><\/script>/g, (_, file) =>
      '<script>\n' + fs.readFileSync(path.join(root, file), 'utf8').replace(/[ \t]+$/gm, '').replace(/<\/script/gi, '<\\/script') + '\n</script>');
}

if (require.main === module) {
  const output = path.join(root, 'calcolo.html');
  if (process.argv.includes('--check')) {
    if (fs.readFileSync(output, 'utf8') !== standalone()) {
      console.error('calcolo.html is outdated. Run node scripts/build-standalone.cjs');
      process.exitCode = 1;
    }
  } else {
    fs.writeFileSync(output, standalone());
    console.log('Generated calcolo.html');
  }
}
module.exports = { standalone };
